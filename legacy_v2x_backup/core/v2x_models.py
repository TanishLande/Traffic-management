"""
V2X Models & Standards Definitions
Directly aligns with SAE J2735 (BSM), ETSI EN 302 637-2 (CAM), and SPaT/MAP.
"""

from typing import List, Dict, Optional, Literal
from pydantic import BaseModel, Field
import time
import uuid

class BSMMessage(BaseModel):
    """
    Basic Safety Message (SAE J2735 / C-V2X PC5 & 5G Uu).
    Broadcast periodically (~10 Hz) by connected vehicle OBUs.
    """
    msg_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    station_id: str
    vehicle_type: Literal["civilian", "emergency", "bus", "truck"] = "civilian"
    x: float
    y: float
    speed: float  # m/s
    heading: float  # 0=North, 90=East, 180=South, 270=West
    acceleration: float = 0.0
    lane_id: str
    brake_active: bool = False
    siren_active: bool = False
    pki_signature: str = "VALID_PKI_CERT_ECC_256"
    timestamp: float = Field(default_factory=time.time)


class VRUMessage(BaseModel):
    """
    Vulnerable Road User Telemetry (pedestrians, cyclists with smartphone/wearables).
    """
    vru_id: str
    vru_type: Literal["pedestrian", "cyclist"] = "pedestrian"
    x: float
    y: float
    speed: float
    heading: float
    crosswalk_id: Optional[str] = None
    in_danger_zone: bool = False
    timestamp: float = Field(default_factory=time.time)


class RSUDetection(BaseModel):
    """
    Roadside Unit (RSU) perception payload from Radar, LiDAR, and Edge Cameras.
    """
    rsu_id: str
    object_id: str
    object_class: str
    x: float
    y: float
    speed: float
    confidence: float
    timestamp: float = Field(default_factory=time.time)


class SafetyAlert(BaseModel):
    """
    Ultra-low latency safety warning generated by Edge AI Inference (< 20ms budget).
    Broadcast to vehicles and VRUs over C-V2X PC5 / 5G Uu.
    """
    alert_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    alert_type: Literal["FCW", "PCW", "EEBL", "EVP_APPROACH", "RED_LIGHT_VIOLATION"]
    severity: Literal["INFO", "WARNING", "CRITICAL"]
    target_vehicle_id: str
    hazard_entity_id: Optional[str] = None
    ttc_seconds: Optional[float] = None  # Time To Collision
    recommended_action: str
    inference_latency_ms: float
    timestamp: float = Field(default_factory=time.time)


class SPaTPhase(BaseModel):
    """
    Signal Phase and Timing (SPaT) broadcast for intersection signal cabinets.
    """
    intersection_id: str = "INT_MAIN_01"
    current_phase: Literal["NS_GREEN", "NS_YELLOW", "EW_GREEN", "EW_YELLOW", "EMERGENCY_CORRIDOR_GREEN"]
    countdown: float
    ns_queue: int = 0
    ew_queue: int = 0
    emergency_preemption_active: bool = False
    preempting_vehicle_id: Optional[str] = None
    cycle_count: int = 0


class LocalDynamicMapState(BaseModel):
    """
    Local Dynamic Map (LDM) maintained by 5G MEC Sensor Fusion layer.
    """
    timestamp: float
    vehicles: List[Dict]
    vrus: List[Dict]
    rsu_sensors: List[Dict]
    signal_phase: SPaTPhase
    active_alerts: List[SafetyAlert]
    kpis: Dict[str, float]
